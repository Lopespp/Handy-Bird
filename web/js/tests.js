  ranged.update(range.top, 0.02);
  check(ranged.birdY === 109, "calibrated top reaches ceiling");
  ranged.update(range.bottom, 0.02);
  check(ranged.birdY === 589, "calibrated bottom reaches floor");
  ranged.setRange({ top: 0.5, bottom: 0.52 });
  check(ranged.range.top === 0.15 && ranged.range.bottom === 0.85, "invalid range falls back to default");
  const played = [];
  const audio = new Sound();
  for (const effect of ["laser", "point", "shatter", "hit", "alarm", "victory", "crash", "pop", "ouch"]) audio[effect] = () => played.push(effect);
