  const powersBefore = spawner.powers.length; spawner.newPipe(1800);
  check(spawner.powers.length === powersBefore, "red plates never bring power-ups");
  const inGap = new Game({ random: () => 0.1, smoothing: 0 }); inGap.powers = [];
  inGap.placePower("triple", 600, 330, 180);
  check(inGap.powers[0].x === 600 + config.pipeWidth / 2 && inGap.powers[0].y !== 330 && Math.abs(inGap.powers[0].y - 330) + config.powerRadius < 90, "power-up sometimes sits inside a pipe gap");
