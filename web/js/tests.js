  check(lives.lives === 2, "invulnerability ignores the next hit");
  lives.invulnerable = 0; lives.hurt(); lives.invulnerable = 0; lives.hurt();
  check(lives.lives === 0 && lives.state === "over", "third hit ends the flight");
