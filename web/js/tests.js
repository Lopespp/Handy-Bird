  const lasers = Object.values(characters).map((character) => character.laser);
  check(lasers.length === 4 && lasers.every((colors) => colors.length === 3) && new Set(lasers.map((colors) => colors[1])).size === 4, "each character has its own laser color");
  check(!document.querySelector(".character-picker em") && !document.getElementById("fps"), "no protagonist tag and a single FPS readout");
  // Cano com bloqueio: corpo continuo ate a barra, sem a ponta aberta de baixo.
  const scene = state.scene;
  check(minionKinds.length === 3 && minionKinds.every((kind) => scene.textures.exists(kind) && scene.textures.getPixelAlpha(0, 0, kind) === 0), "minion sprites load with transparent background");
  check(stages.every(({ boss }) => { const image = scene.bossImages[boss]; return scene.textures.getPixelAlpha(0, 0, boss) === 0 && image.displayWidth >= config[boss].width && image.displayHeight >= config[boss].height; }), "boss sprites load with transparent background and cover their hit area");
  const hudGame = playing(); hudGame.shield = true; scene.drawHud(hudGame);
  check(scene.powerText.text === `${t("power.shield")} 10s`, "HUD counts down the shield");
  const fullscreenButton = document.getElementById("fullscreen");
  check(fullscreenButton.title === `${t("action.fullscreen")} (F)` && fullscreenButton.getAttribute("aria-label") === t("action.fullscreen"), "fullscreen button names its shortcut");
  // Ingles e portugues: a pagina, o placar do jogo e o botao de idioma trocam juntos.
  const originalLanguage = language();
  try {
    setLanguage("pt");
    check(document.documentElement.lang === "pt-BR" && document.getElementById("how-title").textContent === "Como jogar"
      && scene.pointsLabel.text === "PONTOS" && document.getElementById("language").textContent === "EN"
      && stages.map(({ boss }) => t(`boss.${boss}`)).join() === "GUARDIÃO DO VALE,TUBAREI,BICO DE FERRO", "portuguese translates page, game, bosses and toggle");
    setLanguage("en");
    check(document.documentElement.lang === "en" && document.getElementById("how-title").textContent === "How to play"
      && scene.pointsLabel.text === "POINTS" && document.querySelector('[data-i18n="steps.peace"]').textContent === "Two fingers up: pause"
      && stages.map(({ boss }) => t(`boss.${boss}`)).join() === "VALLEY WARDEN,SHARKING,IRONBEAK", "english translates page, game, bosses and toggle");
    check(t("score.time", { score: 7, time: "1:05" }) === "7 points in 1:05" && t("Mensagem pronta") === "Mensagem pronta", "texts fill values and pass through plain messages");
  } finally { setLanguage(originalLanguage); }
  const pipeView = scene.makePipeView();
  const blocked = { x: 400, gapY: 330, gap: 180, red: true, destroyed: false };
  scene.placePipe(pipeView, blocked);
  check(pipeView.blocker.visible && !pipeView.bottom.visible && pipeView.bottomBody.y === 240, "blocked pipe stays whole below the blocker");
  const pipeMeta = scene.pipeMeta[scene.stageKey];
  check(pipeView.ring.visible && pipeView.ring.y === 420 + config.capHeight - pipeMeta.topLip && pipeView.ring.isCropped, "a ring marks the bottom of the blocked gap");
  blocked.destroyed = true; scene.placePipe(pipeView, blocked);
  check(!pipeView.blocker.visible && !pipeView.ring.visible && pipeView.bottom.visible && pipeView.bottomBody.y > 420, "bottom pipe end appears after the blocker breaks");
  pipeView.parts.forEach((part) => part.destroy());
  // Fechar a mao aciona o botao principal, so depois de ver a mao aberta.
  const saved = { mode: state.mode, camera: state.camera, active: state.active, game: state.game };
  const overlay = document.getElementById("overlay"); const startButton = document.getElementById("start");
  const savedUi = { overlay: overlay.hidden, start: startButton.hidden, disabled: startButton.disabled };
  try {
    state.mode = "camera"; state.camera = { stop() {} }; state.active = false;
    overlay.hidden = false; startButton.hidden = false; startButton.disabled = false;
    const hand = Array.from({ length: 21 }, () => ({ x: 0.5, y: 0.5 }));
    startWithFist({ points: hand, closed: true });
    check(!state.active, "a fist that was already closed does not start");
    startWithFist({ points: hand, closed: false }); startWithFist({ points: hand, closed: true });
    check(state.active && state.game.state === "ready", "closing the hand starts the flight");
    // Sinal de paz segurado por um instante pausa; fechar a mao retoma.
    state.game = playing(); state.calibration = null;
    pauseWithPeace({ points: hand, peace: true }, 1000); pauseWithPeace({ points: hand, peace: true }, 1200);
    check(!state.game.paused, "a quick peace sign does not pause");
    pauseWithPeace({ points: hand, peace: true }, 1400);
    check(state.game.paused, "holding the peace sign pauses the flight");
    startWithFist({ points: hand, closed: false }); startWithFist({ points: hand, closed: true });
    check(!state.game.paused && state.game.state === "playing", "closing the hand resumes after the peace pause");
    state.mode = "demo"; state.game.paused = false;
    pauseWithPeace({ points: hand, peace: true }, 2000); pauseWithPeace({ points: hand, peace: true }, 3000);
    check(!state.game.paused, "peace sign only pauses with the webcam");
  } finally {
    Object.assign(state, saved);
    overlay.hidden = savedUi.overlay; startButton.hidden = savedUi.start; startButton.disabled = savedUi.disabled;
  }
  // Sem ?v= nas URLs: o cache e resolvido pelos cabecalhos (sempre revalidar).
  const urls = performance.getEntriesByType("resource").map((entry) => new URL(entry.name)).filter((url) => url.origin === location.origin);
  check(urls.length >= 20 && urls.every((url) => !url.search), "site files load without version query strings");
  return { count: passed.length, passed };
