  flyer.minionTimer = 0.01; flyer.update(0.5, 0.02);
  const [dartwig] = flyer.minions;
  check(flyer.minions.length === 1 && dartwig.kind === "dartwig" && dartwig.x > config.width && flyer.minionTimer >= config.minionEveryMin, "dartwig flies in from the right");
  const dartwigStart = { x: dartwig.x, y: dartwig.y }; flyer.update(0.5, 0.05);
  check(Math.abs(dartwigStart.x - dartwig.x - (flyer.speed + config.minionSpeedBonus) * 0.05) < 1e-9 && dartwig.y === dartwigStart.y, "minions fly straight, a bit faster than pipes");
  flyer.fire();
  for (let step = 0; step < 60 && flyer.minions.length; step += 1) flyer.updateLasers(0.02);
  check(flyer.minions.length === 0 && flyer.defeated === 1 && flyer.lasers.length === 0, "one laser takes a minion down");
  const shielding = playing(); shielding.pipes = [{ x: 470, gapY: 600, gap: 150, red: false }];
  shielding.minions = [{ kind: "dartwig", x: 500, y: 180 }]; shielding.lasers = [{ x: 420, y: 180 }];
  shielding.updateLasers(0.05);
  check(shielding.minions.length === 1 && shielding.lasers.length === 0, "pipes shield minions behind them");
  const bump = playing(); bump.lives = 3; bump.pipes = [{ x: 5000, gapY: 330, gap: 184, red: false, scored: false }];
  bump.minions = [{ kind: "fragcrow", x: config.birdX + 30, y: bump.birdY }]; bump.update(0.5, 0.02);
  check(bump.lives === 2 && bump.minions.length === 0 && bump.invulnerable > 0, "touching a minion costs a life");
  const calm = playing(); calm.score = 30; calm.spawnBoss(); calm.minionTimer = 0; calm.updateMinions(0.05);
  check(calm.minions.length === 0, "no minions while the boss is on screen");
  const stageTwo = playing(); stageTwo.stage = 1; stageTwo.minionTimer = 0; stageTwo.updateMinions(0.01);
  const stageThree = playing(); stageThree.stage = 2; stageThree.minionTimer = 0; stageThree.updateMinions(0.01);
  check(stageTwo.minions[0].kind === "brogull" && stageThree.minions[0].kind === "fragcrow", "brogull on the beach, fragcrow in the storm");
  const slow = playing(); slow.pipes = [{ x: 600, gapY: slow.birdY, gap: 184, red: false, scored: false }];
  slow.slowTimer = 5; slow.update(0.5, 0.05);
  const slowStep = 600 - slow.pipes[0].x;
  slow.slowTimer = 0; const normalStart = slow.pipes[0].x; slow.update(0.5, 0.05);
  check(Math.abs(slowStep * 2 - (normalStart - slow.pipes[0].x)) < 1e-9, "slow motion halves world speed");
  check(document.querySelector('input[name="mode"]').value === "camera", "webcam is the first mode");
  const laser = playing(); laser.pipes = [{ x: 450, gapY: 350, gap: 184, red: false }];
  laser.score = 30; laser.spawnBoss(); laser.lasers = [{ x: 390, y: 180 }]; laser.updateLasers(0.05);
  check(laser.lasers.length === 1, "green pipe penetration during boss");
  laser.boss = null; laser.lasers = [{ x: 390, y: 180 }]; laser.updateLasers(0.05);
  check(laser.lasers.length === 0, "green pipes block outside boss");
  const points = Array.from({ length: 21 }, () => ({ x: 0.5, y: 0.9 }));
  for (const [joint, tip] of [[6, 8], [10, 12], [14, 16], [18, 20]]) { points[joint] = { x: 0.5, y: 0.45 }; points[tip] = { x: 0.5, y: 0.75 }; }
  check(isFistClosed(points), "closed fist detected");
  for (const tip of [8, 12, 16, 20]) points[tip].y = 0.1;
  check(!isFistClosed(points), "open palm detected");
  check(!isPeaceSign(points), "open palm is not a peace sign");
  const peace = Array.from({ length: 21 }, () => ({ x: 0.5, y: 0.9 }));
  for (const [joint, tip] of [[6, 8], [10, 12]]) { peace[joint] = { x: 0.5, y: 0.45 }; peace[tip] = { x: 0.5, y: 0.1 }; }
  for (const [joint, tip] of [[14, 16], [18, 20]]) { peace[joint] = { x: 0.5, y: 0.45 }; peace[tip] = { x: 0.5, y: 0.75 }; }
  check(isPeaceSign(peace) && !isFistClosed(peace), "peace sign detected");
  peace[12] = { x: 0.5, y: 0.75 };
  check(!isPeaceSign(peace), "pointing with one finger is not a peace sign");
  const plain = new OneEuroFilter({ smoothing: 0.1, responsiveness: 0 });
  plain.update(0, 0);
  check(Math.abs(plain.update(1, 0.05) - (1 - Math.exp(-0.5))) < 1e-9, "filter without responsiveness is exponential");
  const adaptive = new OneEuroFilter({ smoothing: 0.1 });
  const lagging = new OneEuroFilter({ smoothing: 0.1, responsiveness: 0 });
  for (const filter of [adaptive, lagging]) { filter.update(0, 0); for (let frame = 0; frame < 6; frame += 1) filter.update(1, 1 / 60); }
  check(adaptive.value > lagging.value + 0.1, "one euro filter follows fast movement");
  const still = new OneEuroFilter({ smoothing: 0.08 });
  still.update(0.5, 0);
  const jitter = Array.from({ length: 60 }, (_, frame) => still.update(0.5 + (frame % 2 ? 0.004 : -0.004), 1 / 30)).slice(30);
  check(Math.max(...jitter) - Math.min(...jitter) < 0.004, "one euro filter attenuates still jitter");
  const hand = (x) => Array.from({ length: 21 }, () => ({ x, y: 0.5 }));
  const lock = new HandLock();
  check(lock.accept(hand(0.3), "Right", 0) && lock.accept(hand(0.32), "Left", 0.03), "hand lock tolerates handedness flicker");
  check(!lock.accept(hand(0.8), "Left", 0.5), "hand lock ignores other hand after tracking loss");
  check(lock.accept(hand(0.8), "Left", 1.6), "hand lock expires");
