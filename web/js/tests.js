  calibration.add(0.3, 0.5); calibration.add(null, 5); calibration.add(0.7, 0.5);
  const range = calibration.result();
  check(calibration.done && Math.abs(range.top - 0.34) < 1e-9 && Math.abs(range.bottom - 0.66) < 1e-9, "calibration keeps comfortable range");
