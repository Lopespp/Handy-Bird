  for (let step = 0; step < 198; step += 1) timed.update(0.5, 0.05);
  check(timed.shield, "shield still up before ten seconds");
  for (let step = 0; step < 4; step += 1) timed.update(0.5, 0.05);
  check(!timed.shield && timed.lives === 1 && timed.state === "playing", "shield expires after ten seconds");
