export const languages = Object.freeze(Object.keys(texts));
const storageKey = "handy-bird-language";

// Começa pela escolha salva; sem ela, português para navegadores em português e
// inglês para todo o resto.
function initialLanguage() {
  try { const saved = localStorage.getItem(storageKey); if (texts[saved]) return saved; } catch {}
  return (navigator.languages ?? [navigator.language]).some((code) => /^pt\b/i.test(code ?? "")) ? "pt" : "en";
}

let current = initialLanguage();
const listeners = new Set();

export function language() { return current; }

// Texto da chave no idioma atual, com {nome} trocado pelos valores. Sem a chave,
// devolve o próprio valor (por exemplo, uma mensagem de erro já pronta).
export function t(key, values = {}) {
  const text = texts[current][key] ?? texts.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match));
}

// Elementos marcados no HTML: data-i18n (texto), data-i18n-html (texto com
// <strong>) e data-i18n-title, -label (aria-label) e -alt (atributos).
export function translatePage(root = document) {
  document.documentElement.lang = current === "pt" ? "pt-BR" : "en";
  document.querySelector('meta[name="description"]')?.setAttribute("content", t("meta.description"));
  for (const element of root.querySelectorAll("[data-i18n]")) element.textContent = t(element.dataset.i18n);
  for (const element of root.querySelectorAll("[data-i18n-html]")) element.innerHTML = t(element.dataset.i18nHtml);
  for (const [attribute, name] of [["i18nTitle", "title"], ["i18nLabel", "aria-label"], ["i18nAlt", "alt"]]) {
    for (const element of root.querySelectorAll(`[data-${attribute.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)}]`)) {
      element.setAttribute(name, t(element.dataset[attribute]));
    }
  }
}

export function onLanguageChange(listener) { listeners.add(listener); }

export function setLanguage(next) {
  if (!texts[next] || next === current) return;
  current = next;
  try { localStorage.setItem(storageKey, next); } catch {}
  translatePage();
  for (const listener of listeners) listener(next);
}
